import Foundation

/// Регулярка со своими границами слов: `\b` в ICU и JS по-разному ведёт себя на кириллице,
/// поэтому `<B>` и `<E>` разворачиваются в явные lookbehind/lookahead.
struct Rx: @unchecked Sendable {
    let re: NSRegularExpression

    init(_ pattern: String) {
        let p = pattern
            .replacingOccurrences(of: "<B>", with: "(?<![а-яa-z])")
            .replacingOccurrences(of: "<E>", with: "(?![а-яa-z])")
        // Шаблоны статические и проверяются тестами: ошибка здесь — ошибка в коде, не в данных.
        re = try! NSRegularExpression(pattern: p)
    }

    func test(_ s: String) -> Bool {
        re.firstMatch(in: s, range: NSRange(s.startIndex..., in: s)) != nil
    }

    /// Группы первого совпадения; nil, если совпадения нет.
    func groups(_ s: String) -> [String?]? {
        guard let m = re.firstMatch(in: s, range: NSRange(s.startIndex..., in: s)) else { return nil }
        return (0..<m.numberOfRanges).map { i in
            Range(m.range(at: i), in: s).map { String(s[$0]) }
        }
    }
}

